process.env.PORT='8107';process.env.DATA_DIR=require('path').join(require('os').tmpdir(),'dp-easy-'+Date.now());
require('fs').mkdirSync(process.env.DATA_DIR,{recursive:true});
process.env.PUBLIC_URL='http://127.0.0.1:8107';process.env.OWNER_EMAILS='owner@x.com';process.env.DEV_UNLOCK='1';
process.env.SYSTEM_SMTP_USER='support@dawnpipe.com';process.env.SYSTEM_SMTP_PASS='sys-app-pass';
process.env.SYSTEM_SMTP_FROM='support@dawnpipe.com';process.env.SYSTEM_SMTP_FROM_NAME='Dawnpipe';
require('./server.js');
const db=require('./lib/db'),auth=require('./lib/auth');
let pass=0,fail=0;const ok=(l,c,x)=>{c?pass++:fail++;console.log((c?'  PASS  ':'  FAIL  ')+l+(!c&&x!==undefined?' -> '+JSON.stringify(x).slice(0,200):''))};
(async()=>{
  await new Promise(r=>setTimeout(r,700));
  const {passHash,salt}=auth.hashPassword('pw');
  const a=db.createAccount({email:'plumber@x.com',passHash,salt});
  db.updateAccount(a.id,{subStatus:'active',tier:'frontdesk',plan:'pro'});
  db.createProfile(a.id,{name:'Bob Plumbing',offer:'plumbing',mailingAddress:'1 Main St'});
  const login=await fetch('http://127.0.0.1:8107/login',{method:'POST',redirect:'manual',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:'email=plumber%40x.com&password=pw'});
  const cookie=(login.headers.get('set-cookie')||'').split(';')[0];
  const api=async(p,b,m)=>{const r=await fetch('http://127.0.0.1:8107'+p,{method:m||(b?'POST':'GET'),headers:{'Content-Type':'application/json',Cookie:cookie},body:b?JSON.stringify(b):undefined});return{status:r.status,json:await r.json().catch(()=>({}))}};
  console.log('== one-click connect ==');
  let r=await api('/api/settings/smtp',{useDawnpipe:true,fromName:'Bob Plumbing'});
  ok('useDawnpipe accepted',r.json.ok&&r.json.mode==='dawnpipe',r.json);
  let st=await api('/api/state');
  ok('state connected, dawnpipe mode',st.json.smtp.connected===true&&st.json.smtp.mode==='dawnpipe',st.json.smtp);
  ok('identity is support@dawnpipe.com',st.json.smtp.user==='support@dawnpipe.com',st.json.smtp.user);
  ok('dawnpipeSendAvailable advertised',st.json.dawnpipeSendAvailable===true);
  console.log('== stored as marker, no creds copied ==');
  const acc=db.getAccount(a.id);
  ok('useDawnpipe marker, no password stored',acc.smtp.useDawnpipe===true&&!acc.smtp.pass,acc.smtp);
  console.log('== shared Dawnpipe domain still gets warmed up ==');
  ok('warmup started on the Dawnpipe domain',acc.warmup&&acc.warmup.enabled&&acc.warmup.domain==='dawnpipe.com',acc.warmup);
  const sending=require('./lib/sending');
  ok('day-one allowance is the warmup floor, not unlimited',sending.warmupAllowance(acc.warmup)===10,sending.warmupAllowance(acc.warmup));
  r=await api('/api/settings/smtp',{useDawnpipe:true,fromName:'Bob Plumbing Again'});
  const acc2=db.getAccount(a.id);
  ok('re-enabling on the same domain does not restart the ramp',acc2.warmup.startDate===acc.warmup.startDate,acc2.warmup);
  console.log('== instant test-connection ==');
  r=await api('/api/settings/smtp/test',{});
  ok('test passes with no password',r.json.ok===true&&r.json.user==='support@dawnpipe.com',r.json);
  console.log('== disconnect clears it ==');
  r=await api('/api/settings/smtp',{disconnect:true});
  ok('disconnect ok',r.json.ok&&r.json.disconnected,r.json);
  st=await api('/api/state');
  ok('now not connected',st.json.smtp.connected===false,st.json.smtp);
  console.log('== own-Gmail path still guarded ==');
  r=await api('/api/settings/smtp',{user:'me@gmail.com',pass:'',fromEmail:'me@gmail.com'});
  st=await api('/api/state');
  ok('saving user with no pass = not connected (own mode)',st.json.smtp.connected===false&&st.json.smtp.mode==='own',st.json.smtp);
  console.log(String.fromCharCode(10)+pass+' passed, '+fail+' failed');process.exit(fail?1:0);
})().catch(e=>{console.error('HARNESS',e);process.exit(1)});
